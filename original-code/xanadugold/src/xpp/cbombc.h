/* ==========================================================================
 *
 *	C_SHIELD_UP()	Raise (activate) the shield.
 *
 *	(The ShieldFree bomb is needed to free the storage allocated by
 *	 incoming letter bombs.)
 *
 * ========================================================================== */

#define	C_SHIELD_UP(TAG, LTAG, ACTION)					\
	C_SHIELD_UP_BEGIN(TAG, LTAG) {					\
	ACTION								\
	} C_SHIELD_UP_END(TAG)

#define	C_SHIELD_UP_BEGIN(TAG, LTAG)					\
	{								\
		int	VAL;						\
									\
		cSetUpErrorListAndSavedPtr(&CAT(TAG,_cShield),		\
			CAT(LTAG,_shieldList)());				\
									\
		if ((VAL = setjmp(*cFetchJmpBuf(&CAT(TAG,_cShield))))) { \
			void *	C_PROBLEM_P = cFetchProblemP(&CAT(TAG,_cShield)); \
			C_PLANT_BOMB_BEGIN(CShieldFree,_cSheildFree) { 	\
				C_ARM_BOMB(_cSheildFree,voidStar,C_PROBLEM_P); \
				{

#define	C_SHIELD_UP_END(TAG)						\
				}					\
			} C_PLANT_BOMB_END				\
		}							\
	}								\
	C_ARM_BOMB(TAG,CShieldStar,&CAT(TAG,_cShield))

