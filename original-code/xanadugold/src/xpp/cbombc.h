/* ==========================================================================
 *
 *		C_RETURN_VOID
 *
 *		C_RETURN_THROUGH(TAG,RETVAL)
 *		C_BREAK_THROUGH(TAG)
 *		C_CONTINUE_THROUGH(TAG)
 *
 *		C_BREAK_FROM_SHIELD
 *		C_CONTINUE_FROM_SHIELD
 *
 *	In the c++ version of the demolition package, an unconditional return
 *	inside a shield causes the ShieldFree bomb's destructor to be
 *	unreachable, so the compiler will warn us of this.  The analog of
 *	"C_SHIELD_RETURN...(retval);" may be used in place of
 *	"return retval;"  to shut the compiler up.  (The if() always takes
 *	the TRUE branch, but convinces the compiler that the other branch
 *	is possible.  A good enough optimizer will squeeze it out, but still
 *	not complain.)
 *
 *	C_RETURN_VOID is something to be returned in C_RETURN_THROUGH() when
 *	used in a routine that doesn't return anything.
 *
 *	Similarly with "break;" and "C_BREAK...;"
 *	Similarly with "continue;" and "C_CONTINUE...;"
 *
 *	In the c version, the problem is worse:
 *
 *	 - C does not automatically generate destructors for us, so we
 *	   must do something to activate them ourselves.  This means we
 *	   MUST use this stuff:
 *	    - not just to keep the warning messages down, but to generate
 *	      correct code.
 *	    - not just when we're leaving a shield, but whenever flow
 *	      passes through shields or bombs via a "return", "break" or
 *	      "continue".
 *
 *       - We must generate destructor activity, not just for the innermost
 *	   bomb or shield, but or all of those we pass through on our way out.
 *	   The support package keeps track of the nesting for us, but we must
 *	   designate the outermost shield or bomb that flow will leave.
 *
 *	So we have the more extensive set of routines:
 *
 *	 - C_RETURN_THROUGH(TAG,RETVAL)	\  Used to leave a shield's ACTION,
 *	 - C_BREAK_THROUGH(TAG)		 } where TAG is from the outermost
 *	 - C_CONTINUE_THROUGH(TAG)	/  INSTALL/PLANT flow is leaving.
 *
 *	 - C_BREAK_FROM_SHIELD		\  Used to leave a shield's ACTION
 *	 - C_CONTINUE_FROM_SHIELD	/  without leaving any INSTALL/PLANTs
 *
 *	NOTE that the compiler will not give warnings for most failures to
 *	use these macros.
 *
 *	NOTE that if TAGs are reused in a nest, these macros will designate
 *	the innermost one, and there is no way to detect the potential error.
 *
 * ========================================================================== */

#define C_RETURN_VOID

#define C_WHATEVER_THROUGH(TAG,WHATEVER)				\
	cBombAbandonThrough(_innermost_bomb, &CAT(TAG,_cBombTag));	\
	if (&CAT(TAG,_cBombTag)) { WHATEVER; }

#define C_RETURN_THROUGH(TAG,RETVAL)					\
		C_WHATEVER_THROUGH(TAG,return RETVAL)

#define C_BREAK_THROUGH(TAG)						\
		C_WHATEVER_THROUGH(TAG,break)

#define C_CONTINUE_THROUGH(TAG)						\
		C_WHATEVER_THROUGH(TAG,continue)

#define C_BREAK_FROM_SHIELD						\
		C_BREAK_THROUGH(_cSheildFree)

#define C_CONTINUE_FROM_SHIELD						\
		C_CONTINUE_THROUGH(_cSheildFree)

