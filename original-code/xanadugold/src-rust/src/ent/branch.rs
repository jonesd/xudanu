// [New Migration Comment] Marker for an evicted branch. In the original, a
// stub replaced the real BranchDescription in memory, sharing "the same hash
// and flockInfo" as the object it replaced (Abraham::becomeStub, shephx.cxx
// lines 121-131; per-subclass stubbing constructors were generated by the
// SHEPHERD macros, shephx.hxx lines 123-139). Any method call on the stub
// faulted the real object back from disk via its FlockInfo locator.
//
// The original stub cached hashForEqual() — an identity hash. We cache the
// branch's contents hash instead, so the stub is self-sufficient for
// fault-in: the spill key is (id << 32) | hash, and a faulted-in branch is
// verified by recomputing its contents hash against the stub's. This is the
// FlockInfo role ("the object that describes the state of this flock wrt
// disk", shephx.hxx lines 312-317) collapsed into a single u32.
#[derive(Debug, Clone)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub struct BranchStub {
    // Contents hash at evict time; doubles as the spill locator (see above).
    pub hash: u32,
}

// [New Migration Comment] Encodes the "become" transition point explicitly.
// In the original C++, this was invisible — the same memory address would
// hold either a BranchDescription or a BranchDescriptionStub, with the vtable
// pointer swapped via changeClassToThatOf (tofux.ixx line 22-34). Making the
// transition explicit in the type system is the Rust equivalent.
#[derive(Debug, Clone)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize))]
pub enum BranchState {
    Materialized(Branch),
    Stub(BranchStub),
}

