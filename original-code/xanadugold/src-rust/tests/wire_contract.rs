//! Wire protocol contract (companion to docs/wire-protocol.html).
//!
//! The protocol is a compatibility contract: within api_version 1,
//! changes are ADDITIVE ONLY — new operations may be appended, but
//! an existing operation's name, code, or payload shape must not
//! change or disappear. Third UIs and integrations build on this.
//!
//! This test pins the operation table. Adding an operation? The
//! test fails with the diff — update the pinned table below in the
//! same commit, deliberately. Removing or renumbering one? That is
//! a contract break: it requires an api_version bump and a
//! deprecation cycle, not a pin edit.

