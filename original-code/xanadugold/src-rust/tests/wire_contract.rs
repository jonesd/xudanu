#[test]
fn operation_table_matches_contract_pin() {
    let live: Vec<(u16, String)> = OperationCode::OP_CODE_TABLE
        .iter()
        .map(|(code, op)| (*code, format!("{:?}", op)))
        .collect();
    let pinned: Vec<(u16, String)> = PINNED
        .iter()
        .map(|(c, n)| (*c, n.to_string()))
        .collect();

    let added: Vec<_> = live.iter().filter(|l| !pinned.contains(l)).collect();
    let removed: Vec<_> = pinned.iter().filter(|p| !live.contains(p)).collect();

    assert!(
        removed.is_empty(),
        "WIRE CONTRACT BREAK: operations removed or renumbered: {:?}\n\
         Removing or renumbering breaks every third-party client. This \
         requires an api_version bump and a deprecation cycle.",
        removed
    );
    assert!(
        added.is_empty(),
        "New operations detected: {:?}\n\
         Additions are welcome — update the PINNED table in this file \
         in the same commit so the contract pin stays current.",
        added
    );
}
